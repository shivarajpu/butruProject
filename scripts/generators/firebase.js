/**
 * firebase — copies each client's Firebase config into the two places the
 * native SDKs look for it, and keeps the Xcode project able to bundle it.
 *
 * ── Where the config has to be ───────────────────────────────────────────────
 *
 *   Android   `android/app/src/<flavor>/google-services.json`
 *             The Google Services Gradle plugin reads the file from the flavor
 *             source set that is being compiled, and turns it into the string
 *             resources the Firebase SDK reads at runtime. Because the flavor
 *             directory is per client, two clients never share a project.
 *
 *   iOS       `ios/butruProject/GoogleService-Info.plist`
 *             The Firebase SDK looks the file up by name in the main bundle, so
 *             it has to be a *resource* of the app target — which is why the
 *             .pbxproj gets a reference to it (see `ensurePbxprojResource`).
 *             There is only one iOS build at a time, so one slot is enough; the
 *             file is rewritten for whichever client is being built.
 *
 * ── Why nothing here is allowed to fail the build ────────────────────────────
 *
 * Push is optional per client. A client with `firebase.enabled: false` must
 * still build and install, so the generator writes a *placeholder* config in
 * that case: the iOS app needs a plist to exist for the build input to
 * resolve, and a placeholder keeps the file resolvable while making the
 * missing configuration obvious in the device log.
 *
 * ── Why stale config is never deleted ────────────────────────────────────────
 *
 * An earlier version removed `google-services.json` from the flavor directory
 * when a client had Firebase switched off, so that a tenant's Firebase project
 * could not leak into another tenant's build. That was wrong: developers drop
 * the file into the flavor directory by hand all the time, and a sync that
 * deletes it destroys work that cannot be recovered — the file has to be
 * downloaded from the Firebase console again. The leak it was guarding against
 * is now prevented at the other end: the Google Services plugin is applied
 * only when the client has `firebase.enabled = true` (see
 * `android/app/build.gradle`), so a leftover file is ignored by the build.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { ROOT, loadRegistry, resolveClient } = require('../lib/clientRegistry');

// The iOS bundle resource. Referenced by the .pbxproj, so it must exist.
const IOS_BUNDLE_PLIST = path.join(
  ROOT,
  'ios',
  'butruProject',
  'GoogleService-Info.plist',
);

const PBXPROJ = path.join(
  ROOT,
  'ios',
  'butruProject.xcodeproj',
  'project.pbxproj',
);

// Stable 24-hex ids, unique within the .pbxproj. Checked before writing so a
// collision can never happen silently.
const IDS = {
  buildFile: 'F0F1E00000000000000000001',
  fileRef: 'F0F1E00000000000000000002',
};

/**
 * A syntactically valid plist that configures nothing.
 *
 * The Firebase SDK reads this file at launch. With a placeholder it simply
 * fails to configure — it does not crash — and the JS side reports "no Firebase
 * App" instead, which is the honest signal that push is off for this build.
 */
function renderPlaceholderPlist(client) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<!--
	  PLACEHOLDER — generated by \`npm run clients:sync\`.

	  Client "${client.id}" has no Firebase config, so push notifications are
	  off for this build. To enable them:
	    1. create a Firebase project for ${client.displayName}
	    2. download GoogleService-Info.plist into
	       clients/firebase/${client.id}/ios/GoogleService-Info.plist
	    3. set "firebase": { "enabled": true } for this client in
	       clients/clients.json
	    4. run: npm run clients:sync -- --client ${client.id}
	-->
	<key>BUNDLE_ID</key>
	<string>com.example.placeholder</string>
	<key>PROJECT_ID</key>
	<string>placeholder-not-configured</string>
	<key>GOOGLE_APP_ID</key>
	<string>1:000000000000:ios:0000000000000000</string>
	<key>GCM_SENDER_ID</key>
	<string>000000000000</string>
</dict>
</plist>
`;
}

/**
 * True when the file in the iOS bundle slot is the placeholder this script
 * writes, rather than a real GoogleService-Info.plist.
 */
function isPlaceholderPlist(filePath) {
  try {
    return fs.readFileSync(filePath, 'utf8').includes('PLACEHOLDER');
  } catch {
    return false;
  }
}

/**
 * The BUNDLE_ID inside a GoogleService-Info.plist.
 *
 * The iOS bundle slot is shared between clients — only one iOS build runs at a
 * time — so the file that is sitting there may well belong to another client.
 * Reading the bundle id out of it is what tells them apart.
 */
function plistBundleId(filePath) {
  try {
    const match = fs
      .readFileSync(filePath, 'utf8')
      .match(/<key>BUNDLE_ID<\/key>\s*<string>([^<]*)<\/string>/);
    return match ? match[1].trim() : null;
  } catch {
    return null;
  }
}

/**
 * Resolves one client's Firebase source files.
 *
 * A client has push when it has a config file. The file can be in either of
 * the two places a developer puts it:
 *
 *   - `clients/firebase/<client>/android/google-services.json` — the canonical
 *     location, the one this script copies from;
 *   - `android/app/src/<flavor>/google-services.json` — hand-placed, which is
 *     how most people drop it in the first time.
 *
 * `firebase.enabled: true` says "a file will be there" — the sync fails when it
 * is not, because that is a mistake in the repository rather than a state to
 * work around. `firebase.enabled: false` (or missing) means "no file is
 * expected": if one turns up anyway, it is used, because someone clearly meant
 * to turn push on. The flag never deletes a file.
 */
function resolveFirebaseFiles(client) {
  const config = client.firebase || {};
  const explicitlyEnabled = config.enabled === true;

  const canonicalAndroid = config.androidFile
    ? path.join(ROOT, config.androidFile)
    : null;
  const canonicalIos = config.iosFile
    ? path.join(ROOT, config.iosFile)
    : null;
  const flavorAndroid = androidTarget(client);

  const androidSource =
    (canonicalAndroid && fs.existsSync(canonicalAndroid) && canonicalAndroid) ||
    (fs.existsSync(flavorAndroid) && flavorAndroid) ||
    null;

  const bundleSlotIsMine =
    fs.existsSync(IOS_BUNDLE_PLIST) &&
    !isPlaceholderPlist(IOS_BUNDLE_PLIST) &&
    plistBundleId(IOS_BUNDLE_PLIST) === (client.ios && client.ios.bundleId);

  const iosSource =
    (canonicalIos && fs.existsSync(canonicalIos) && canonicalIos) ||
    (bundleSlotIsMine && IOS_BUNDLE_PLIST) ||
    null;

  if (explicitlyEnabled) {
    if (!androidSource) {
      throw new Error(
        `[firebase] client "${client.id}" has firebase.enabled = true but\n` +
          `          ${config.androidFile || '(no firebase.androidFile)'} does not exist.\n` +
          '          Download it from the Firebase console (Project settings → Your apps → google-services.json).',
      );
    }
    if (!iosSource) {
      throw new Error(
        `[firebase] client "${client.id}" has firebase.enabled = true but\n` +
          `          ${config.iosFile || '(no firebase.iosFile)'} does not exist.\n` +
          '          Download it from the Firebase console (Project settings → Your apps → GoogleService-Info.plist).',
      );
    }
    return { enabled: true, androidSource, iosSource, autoEnabled: false };
  }

  if (androidSource || iosSource) {
    return { enabled: true, androidSource, iosSource, autoEnabled: true };
  }

  return {
    enabled: false,
    androidSource: null,
    iosSource: null,
    autoEnabled: false,
  };
}

// ── Android ─────────────────────────────────────────────────────────────────

function androidTarget(client) {
  return path.join(
    ROOT,
    'android',
    'app',
    'src',
    client.flavor,
    'google-services.json',
  );
}

function writeAndroidConfig(client, files, { check, log }) {
  const target = androidTarget(client);

  if (!files.enabled) {
    // Never delete the file. It may be the only copy of a config that was
    // downloaded from the Firebase console by hand, and it cannot be
    // recovered. The build ignores it — Gradle applies the Google Services
    // plugin only when the client has firebase.enabled = true — so leaving it
    // in place is safe.
    if (fs.existsSync(target)) {
      log(
        `  firebase → ${rel(target)} is present but firebase.enabled is false for "${client.id}" — the build ignores it. Set "firebase": { "enabled": true } for this client in clients/clients.json to use it.`,
      );
    }
    return [];
  }

  if (check) return [target];

  if (!files.androidSource) {
    log(
      `  firebase → no google-services.json for "${client.id}" — push stays off on Android. Put the file at ${rel(path.join(ROOT, client.firebase.androidFile))} or at ${rel(target)}.`,
    );
    return [];
  }

  if (files.androidSource !== target) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.copyFileSync(files.androidSource, target);
    log(`  firebase → ${rel(target)}`);
  } else {
    log(`  firebase → ${rel(target)} (already in place)`);
  }
  return [target];
}

// ── iOS ─────────────────────────────────────────────────────────────────────

function writeIosBundlePlist(client, files, { check, log }) {
  if (check) return [IOS_BUNDLE_PLIST];

  if (files.enabled && files.iosSource) {
    if (files.iosSource !== IOS_BUNDLE_PLIST) {
      fs.mkdirSync(path.dirname(IOS_BUNDLE_PLIST), { recursive: true });
      fs.copyFileSync(files.iosSource, IOS_BUNDLE_PLIST);
      log(`  firebase → ${rel(IOS_BUNDLE_PLIST)} (${client.id})`);
    } else {
      log(`  firebase → ${rel(IOS_BUNDLE_PLIST)} (already in place)`);
    }
  } else {
    // No iOS config for this client. The build input still has to exist, so
    // the placeholder goes in — it configures nothing and says exactly what is
    // missing. A config that belongs to *another* client is replaced here on
    // purpose: the slot is shared, and one tenant's Firebase project must
    // never be bundled into another tenant's app.
    fs.mkdirSync(path.dirname(IOS_BUNDLE_PLIST), { recursive: true });
    fs.writeFileSync(
      IOS_BUNDLE_PLIST,
      renderPlaceholderPlist(client),
      'utf8',
    );
    log(
      `  firebase → ${rel(IOS_BUNDLE_PLIST)} (placeholder — push is off on iOS for "${client.id}")`,
    );
  }

  return [IOS_BUNDLE_PLIST];
}

/**
 * Warns when a client has a Firebase config on disk that will not be used,
 * because `firebase.enabled` is still false. This is the single most common
 * reason push "does not work" after the files were downloaded: the files are
 * there, the flag is not.
 */
function warnAboutUnusedConfig(client, log) {
  const config = client.firebase || {};
  const androidSource = config.androidFile
    ? path.join(ROOT, config.androidFile)
    : null;
  const iosSource = config.iosFile ? path.join(ROOT, config.iosFile) : null;

  if (androidSource && fs.existsSync(androidSource)) {
    log(
      `  firebase → ${rel(androidSource)} exists but firebase.enabled is false for "${client.id}" — push stays OFF. Set "firebase": { "enabled": true } for this client in clients/clients.json.`,
    );
  }
  if (iosSource && fs.existsSync(iosSource)) {
    log(
      `  firebase → ${rel(iosSource)} exists but firebase.enabled is false for "${client.id}" — push stays OFF. Set "firebase": { "enabled": true } for this client in clients/clients.json.`,
    );
  }
}

// ── Xcode project ───────────────────────────────────────────────────────────

/**
 * Adds `GoogleService-Info.plist` to the app target's Copy Bundle Resources
 * phase, and to the project navigator.
 *
 * Without this the file is never copied into the .app, the Firebase SDK
 * cannot find it at launch, and push silently does nothing on iOS — the kind
 * of failure that looks like a server problem.
 *
 * Idempotent: running it twice changes nothing.
 */
function ensurePbxprojResource({ check, log }) {
  if (!fs.existsSync(PBXPROJ)) {
    throw new Error('[firebase] ios/butruProject.xcodeproj/project.pbxproj not found');
  }

  let content = fs.readFileSync(PBXPROJ, 'utf8');

  if (content.includes(IDS.buildFile)) {
    return false;
  }

  for (const id of Object.values(IDS)) {
    if (content.includes(id)) {
      throw new Error(
        `[firebase] id collision: ${id} already exists in project.pbxproj. ` +
          'Change the ids in scripts/generators/firebase.js and re-run.',
      );
    }
  }

  const buildFile =
    '\t\t' +
    `${IDS.buildFile} /* GoogleService-Info.plist in Resources */ = {isa = PBXBuildFile; ` +
    `fileRef = ${IDS.fileRef} /* GoogleService-Info.plist */; };`;

  const fileRef =
    '\t\t' +
    `${IDS.fileRef} /* GoogleService-Info.plist */ = {isa = PBXFileReference; ` +
    'fileEncoding = 4; lastKnownFileType = text.plist.xml; ' +
    'name = "GoogleService-Info.plist"; path = "butruProject/GoogleService-Info.plist"; ' +
    'sourceTree = "<group>"; };';

  // 1. The two object declarations.
  content = content.replace(
    '/* Begin PBXBuildFile section */',
    '/* Begin PBXBuildFile section */\n' + buildFile,
  );
  content = content.replace(
    '/* Begin PBXFileReference section */',
    '/* Begin PBXFileReference section */\n' + fileRef,
  );

  // 2. The Copy Bundle Resources phase — this is what actually puts the file
  //    inside the .app.
  const resourcesAnchor =
    '/* Resources */ = {\n\t\t\tisa = PBXResourcesBuildPhase;\n\t\t\tbuildActionMask = 2147483647;\n\t\t\tfiles = (\n';
  if (!content.includes(resourcesAnchor)) {
    throw new Error(
      '[firebase] Could not find the Resources build phase in project.pbxproj.\n' +
        '  Add GoogleService-Info.plist to the app target\'s "Copy Bundle Resources"\n' +
        '  build phase in Xcode, or restore the project file.',
    );
  }
  content = content.replace(
    resourcesAnchor,
    resourcesAnchor +
      '\t\t\t\t' +
      `${IDS.buildFile} /* GoogleService-Info.plist in Resources */,\n`,
  );

  // 3. The project navigator group, so the file is visible in Xcode.
  const groupAnchor =
    /([0-9A-F]{24}) \/\* butruProject \*\/ = \{\n\t\t\tisa = PBXGroup;\n\t\t\tchildren = \(\n/;
  if (!groupAnchor.test(content)) {
    throw new Error(
      '[firebase] Could not find the butruProject group in project.pbxproj.\n' +
        '  Add the file to the project in Xcode instead.',
    );
  }
  content = content.replace(
    groupAnchor,
    (match) =>
      match.replace(
        'children = (\n',
        'children = (\n\t\t\t\t' +
          `${IDS.fileRef} /* GoogleService-Info.plist */,\n`,
      ),
  );

  if (check) {
    log('  firebase → would add GoogleService-Info.plist to the Xcode Resources phase');
    return true;
  }

  fs.writeFileSync(PBXPROJ, content, 'utf8');
  log('  firebase → ios/butruProject.xcodeproj/project.pbxproj (Resources phase)');
  return true;
}

// ── entry point ─────────────────────────────────────────────────────────────

function generate({ resolved, check, log = () => {} }) {
  const registry = loadRegistry();
  const written = [];

  // Every client gets its Android config, not just the one being built —
  // otherwise switching clients would need two syncs before the build was
  // correct.
  const filesByClient = {};
  Object.keys(registry.clients).forEach(id => {
    const client = resolveClient(id, registry);
    const files = resolveFirebaseFiles(client);
    filesByClient[id] = files;
    if (files.autoEnabled) {
      log(
        `  firebase → ${client.id}: a Firebase config was found, so push is ON ` +
          'for this client (firebase.enabled was false — set it to true to make ' +
          'the intent explicit).',
      );
    }
    if (!files.enabled) warnAboutUnusedConfig(client, log);
    written.push(...writeAndroidConfig(client, files, { check, log }));
  });

  // iOS has one build at a time, so one bundle slot: the active client's file.
  const activeFiles = filesByClient[resolved.id];
  if (!activeFiles) {
    throw new Error(
      `[firebase] active client "${resolved.id}" is not in the registry`,
    );
  }
  written.push(...writeIosBundlePlist(resolved, activeFiles, { check, log }));

  ensurePbxprojResource({ check, log });

  return written;
}

function rel(absolutePath) {
  return path.relative(ROOT, absolutePath);
}

module.exports = {
  generate,
  renderPlaceholderPlist,
  resolveFirebaseFiles,
  ensurePbxprojResource,
  IOS_BUNDLE_PLIST,
  IDS,
};
