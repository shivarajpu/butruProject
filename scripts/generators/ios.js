/**
 * ios — writes the xcconfig layer that makes an iOS build per-client, and one
 * Xcode scheme per client so the scheme dropdown itself is the flavour picker.
 *
 * ── Where the client identity comes from ────────────────────────────────────
 * The client-specific values arrive through an `.xcconfig` include chain:
 *
 *   Config/Shared.xcconfig          ← committed, hand-editable, RN defaults
 *     └─ Config/Client.xcconfig      ← generated, git-ignored  (one per client)
 *          └─ Config/Clients/<id>.xcconfig  ← committed, one per client
 *
 * `Client.xcconfig` is a one-line `#include` of the selected client's file, so
 * switching clients is a two-line rewrite. Nothing in the .pbxproj is touched
 * after initial setup, and any number of clients can be archived from CI in
 * parallel.
 *
 * ── Why there is a scheme per client after all ──────────────────────────────
 * Selecting a client used to mean running `clients:sync --client <id>` first —
 * fine from the terminal, invisible from Xcode, where the dropdown showed only
 * `butruProject` and gave no hint which app you were about to archive.
 *
 * So we now emit one *shared* scheme per client (Schemes/<id>.xcscheme) whose
 * Build pre-action runs `clients:sync --client <id>` before the build reads the
 * xcconfig. Shared schemes live in `xcshareddata/xcschemes/`, NOT in the
 * .pbxproj, so this adds zero pbxproj weight no matter how many clients exist —
 * the same reason the xcconfig split exists. Picking the scheme is now the one
 * action that sets bundle id, display name, Info.plist, icon and `.env`.
 *
 * ── What each client gets ───────────────────────────────────────────────────
 *   PRODUCT_BUNDLE_IDENTIFIER         com.company.clienta
 *   PRODUCT_NAME                      ClientA
 *   ASSETCATALOG_COMPILER_APPICON_NAME AppIcon_ClientA
 *   CLIENT_ENV_FILE                   .env.clienta        → babel picks it up
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { ROOT, loadRegistry, resolveClient, metroPort, rel } = require('../lib/clientRegistry');
const { generateIcons, hasMaster, iosAssetName } = require('./icons');

const CONFIG_DIR = path.join(ROOT, 'ios', 'Config');
const CLIENTS_DIR = path.join(CONFIG_DIR, 'Clients');

// Shared schemes live here — one per client. Outside the .pbxproj on purpose.
const SCHEMES_DIR = path.join(
  ROOT,
  'ios',
  'butruProject.xcodeproj',
  'xcshareddata',
  'xcschemes',
);
// The one app target (app runs as butruProject.app for every client) and the
// test target, referenced by the scheme's build/test actions.
const APP_BLUEPRINT_ID = '13B07F861A680F5B00A75B9A';
const TESTS_BLUEPRINT_ID = '00E356ED1AD99517003FC87E';
// The old single scheme: superseded by the per-client ones. Removed on sync so
// Xcode's dropdown shows only real flavours.
const LEGACY_SCHEME = 'butruProject.xcscheme';

// ── ios/Config/Clients/<id>.xcconfig  (committed, one per client) ────────────

/**
 * An xcconfig is NOT a C preprocessor file, despite `#include` looking like one.
 * `#` starts a directive, so a `# comment` line becomes
 *
 *     error: unsupported preprocessor directive 'Replaces'
 *
 * and fails the build with a wall of errors that says nothing about the real
 * mistake. Only `//` and `/* *\/` are comments here. Checking before write turns
 * a 40-line mystery into one clear line.
 */
function assertValidXcconfig(text, label) {
  const bad = text
    .split('\n')
    .map((line, i) => ({ line, n: i + 1 }))
    .filter(({ line }) => /^\s*#/.test(line) && !/^\s*#include/.test(line));

  if (bad.length > 0) {
    throw new Error(
      `[ios] ${label} uses '#' for comments, which xcconfig treats as a ` +
        `preprocessor directive. Use '//' instead. Offending lines: ` +
        bad.map((b) => b.n).join(', '),
    );
  }
}

function renderClientXcconfig(client, registry) {
  const isDefault = client.id === registry.defaultClient;
  const appIcon = client.ios.icon ? iosAssetName(client.ios.icon) : 'AppIcon';
  const version = client.ios.version || '1.0';
  const team = client.ios.teamId || '';
  const port = metroPort(client.id, registry);

  // Built outside the template literal — a nested one here confuses the parser
  // and reads badly besides.
  const signing = team
    ? [
        '',
        '// ── Signing ───────────────────────────────────────────────────────────────',
        '// Each client can sit under a different Apple Developer account.',
        `DEVELOPMENT_TEAM = ${team}`,
      ].join('\n')
    : '';

  const defaultNote = isDefault
    ? '\n// (default client — matches what this app shipped with before flavours)'
    : '';

  return [
    '// ─────────────────────────────────────────────────────────────────────────',
    `// Client: ${client.displayName}`,
    '//',
    '// Generated by `npm run clients:sync` from clients/clients.json.',
    '// Committed on purpose — this is the permanent record of this client\'s store',
    '// identity. The per-build wrapper that selects it is Config/Client.xcconfig.',
    '//',
    '// Note: PRODUCT_NAME is deliberately NOT set here. The app keeps building as',
    '// butruProject.app; what the user sees on the home screen comes from',
    "// CLIENT_DISPLAY_NAME via Info.plist's CFBundleDisplayName. Changing",
    '// PRODUCT_NAME would rename the executable and risk breaking the React Native',
    '// bundle script phase for no user-visible gain.',
    '// ─────────────────────────────────────────────────────────────────────────',
    '',
    '// ── Store identity ───────────────────────────────────────────────────────',
    `PRODUCT_BUNDLE_IDENTIFIER = ${client.ios.bundleId}`,
    `MARKETING_VERSION = ${version}`,
    `CURRENT_PROJECT_VERSION = 1${defaultNote}`,
    '',
    '// ── Per-client Info.plist ──────────────────────────────────────────────',
    '// One plist per client, so a client can carry its own permissions, URL',
    '// schemes or background modes without touching anyone else\'s build.',
    '// Shared.xcconfig holds the default client\'s path as a fallback.',
    `INFOPLIST_FILE = butruProject/Clients/${client.id}/Info.plist`,
    '',
    '// ── Home-screen label ───────────────────────────────────────────────────',
    '// Replaces the hardcoded "Butru" that used to sit in Info.plist.',
    `CLIENT_DISPLAY_NAME = ${client.displayName}`,
    '',
    '// ── Native store identity ────────────────────────────────────────────────',
    '// Info.plist substitutes these into ClientStoreId / ClientStoreSlug, and',
    '// AppDelegate hands them to JS at runtime. They are baked into the binary',
    '// (not the bundle), so a client app keeps its own store identity even if',
    '// another client\'s Metro is serving 8081.',
    `CLIENT_STORE_ID = ${client.api.storeId}`,
    `CLIENT_STORE_SLUG = ${client.api.storeSlug}`,
    '',
    '// ── App icon ────────────────────────────────────────────────────────────',
    '// Points at an appiconset inside the existing Images.xcassets, so no new',
    '// resource has to be added to the Xcode project.',
    `ASSETCATALOG_COMPILER_APPICON_NAME = ${appIcon}`,
    signing,
    '',
    '// ── Build-time environment ──────────────────────────────────────────────',
    '// Read by babel.config.js so the JS bundle is built against this client API.',
    '// Xcode exports build settings into the environment of every Run Script phase,',
    '// which is where the React Native bundle step picks this up. If that ever stops',
    "// working, babel reads the client id from clients/active.json instead.",
    `CLIENT_ID = ${client.id}`,
    '',
    '// ── Dev packager port ──────────────────────────────────────────────────',
    '// Info.plist substitutes $(RCT_METRO_PORT) into MetroPort, and AppDelegate',
    '// feeds that to RCTBundleURLProvider. Without it the app asks for 8081',
    "// (React's compiled-in default), so a client on any other port fails with",
    '// "No script URL provided" even though its bundler is running fine.',
    '// Must match the port `npm run start -- --client <id>` uses.',
    `RCT_METRO_PORT = ${port}`,
    '',
  ].join('\n');
}

// ── ios/Config/Client.xcconfig  (generated, git-ignored) ─────────────────────

/**
 * The only per-build file. Selecting a different client is a two-line change
 * here, which is what keeps 50 clients from needing 50 schemes.
 */
function renderActiveXcconfig(resolved) {
  return `// AUTO-GENERATED by \`npm run clients:sync\` — do not edit, do not commit.
// Regenerate: npm run clients:sync -- --client ${resolved.id}
#include "Clients/${resolved.id}.xcconfig"

// Which generated env file babel.config.js should inline. The file holds this
// client's single API base URL — there is no environment axis.
CLIENT_ENV_FILE = .env.${resolved.id}
`;
}

// ── ios/butruProject.xcodeproj/xcshareddata/xcschemes/<id>.xcscheme ──────────

/**
 * A shared scheme whose name IS the client id, so Xcode's scheme dropdown reads
 * as the list of flavours. Its only job beyond the stock scheme is the Build
 * pre-action: before Xcode compiles, it rewrites Config/Client.xcconfig to point
 * at this client, so bundle id / display name / Info.plist / icon / env all come
 * out right whether you hit Run, Test or Archive.
 *
 * `SRCROOT` is the ios/ directory (Xcode sets it for scheme pre-actions), so the
 * repo root — where the sync script lives — is one level up. `PROJECT_DIR` is a
 * fallback for the rare Xcode version that exports one but not the other.
 *
 * Node is resolved the same way the React Native bundle phase does it: source
 * `.xcode.env` (which sets NODE_BINARY from `command -v node`) then
 * `.xcode.env.local` (which pins an absolute path, written per machine and
 * git-ignored). This matters because Xcode launched from Finder/Dock inherits a
 * minimal PATH without Homebrew/nvm, so a bare `node` exits 127.
 */
function renderScheme(client) {
  const id = client.id;
  // Built as plain strings: `${SRCROOT:-$PROJECT_DIR}`, `${NODE_BINARY:-node}`
  // and the `2>/dev/null` redirects must survive into the shell verbatim, so
  // they must NOT be template-literal interpolations.
  const syncScript = [
    // Xcode.app from Finder has no Homebrew/nvm on PATH — add the usual homes.
    'export PATH=&quot;/opt/homebrew/bin:/usr/local/bin:$PATH&quot;',
    'cd &quot;${SRCROOT:-$PROJECT_DIR}/..&quot; || exit 1',
    // Guard each source: POSIX `.` on a missing file aborts a non-interactive
    // shell outright, so an absent .xcode.env.local (fresh clone) would kill the
    // pre-action before node ever runs.
    '[ -f &quot;$SRCROOT/.xcode.env&quot; ] &amp;&amp; . &quot;$SRCROOT/.xcode.env&quot;',
    '[ -f &quot;$SRCROOT/.xcode.env.local&quot; ] &amp;&amp; . &quot;$SRCROOT/.xcode.env.local&quot;',
    `&quot;\${NODE_BINARY:-node}&quot; scripts/sync-clients.js --client ${id}`,
  ].join('; ');

  return `<?xml version="1.0" encoding="UTF-8"?>
<Scheme
   LastUpgradeVersion = "1210"
   version = "1.3">
   <BuildAction
      parallelizeBuildables = "YES"
      buildImplicitDependencies = "YES">
      <PreActions>
         <ExecutionAction
            ActionType = "Xcode.IDEStandardExecutionActionsCore.ExecutionActionType.ShellScriptAction">
            <ActionContent
               title = "Select client: ${id}"
               scriptText = "${syncScript}">
               <EnvironmentBuildable>
                  <BuildableReference
                     BuildableIdentifier = "primary"
                     BlueprintIdentifier = "${APP_BLUEPRINT_ID}"
                     BuildableName = "butruProject.app"
                     BlueprintName = "butruProject"
                     ReferencedContainer = "container:butruProject.xcodeproj">
                  </BuildableReference>
               </EnvironmentBuildable>
            </ActionContent>
         </ExecutionAction>
      </PreActions>
      <BuildActionEntries>
         <BuildActionEntry
            buildForTesting = "YES"
            buildForRunning = "YES"
            buildForProfiling = "YES"
            buildForArchiving = "YES"
            buildForAnalyzing = "YES">
            <BuildableReference
               BuildableIdentifier = "primary"
               BlueprintIdentifier = "${APP_BLUEPRINT_ID}"
               BuildableName = "butruProject.app"
               BlueprintName = "butruProject"
               ReferencedContainer = "container:butruProject.xcodeproj">
            </BuildableReference>
         </BuildActionEntry>
      </BuildActionEntries>
   </BuildAction>
   <TestAction
      buildConfiguration = "Debug"
      selectedDebuggerIdentifier = "Xcode.DebuggerFoundation.Debugger.LLDB"
      selectedLauncherIdentifier = "Xcode.DebuggerFoundation.Launcher.LLDB"
      shouldUseLaunchSchemeArgsEnv = "YES">
      <Testables>
         <TestableReference
            skipped = "NO">
            <BuildableReference
               BuildableIdentifier = "primary"
               BlueprintIdentifier = "${TESTS_BLUEPRINT_ID}"
               BuildableName = "butruProjectTests.xctest"
               BlueprintName = "butruProjectTests"
               ReferencedContainer = "container:butruProject.xcodeproj">
            </BuildableReference>
         </TestableReference>
      </Testables>
   </TestAction>
   <LaunchAction
      buildConfiguration = "Debug"
      selectedDebuggerIdentifier = "Xcode.DebuggerFoundation.Debugger.LLDB"
      selectedLauncherIdentifier = "Xcode.DebuggerFoundation.Launcher.LLDB"
      launchStyle = "0"
      useCustomWorkingDirectory = "NO"
      ignoresPersistentStateOnLaunch = "NO"
      debugDocumentVersioning = "YES"
      debugServiceExtension = "internal"
      allowLocationSimulation = "YES">
      <BuildableProductRunnable
         runnableDebuggingMode = "0">
         <BuildableReference
            BuildableIdentifier = "primary"
            BlueprintIdentifier = "${APP_BLUEPRINT_ID}"
            BuildableName = "butruProject.app"
            BlueprintName = "butruProject"
            ReferencedContainer = "container:butruProject.xcodeproj">
         </BuildableReference>
      </BuildableProductRunnable>
   </LaunchAction>
   <ProfileAction
      buildConfiguration = "Release"
      shouldUseLaunchSchemeArgsEnv = "YES"
      savedToolIdentifier = ""
      useCustomWorkingDirectory = "NO"
      debugDocumentVersioning = "YES">
      <BuildableProductRunnable
         runnableDebuggingMode = "0">
         <BuildableReference
            BuildableIdentifier = "primary"
            BlueprintIdentifier = "${APP_BLUEPRINT_ID}"
            BuildableName = "butruProject.app"
            BlueprintName = "butruProject"
            ReferencedContainer = "container:butruProject.xcodeproj">
         </BuildableReference>
      </BuildableProductRunnable>
   </ProfileAction>
   <AnalyzeAction
      buildConfiguration = "Debug">
   </AnalyzeAction>
   <ArchiveAction
      buildConfiguration = "Release"
      revealArchiveInOrganizer = "YES">
   </ArchiveAction>
</Scheme>
`;
}

// ── entry point ──────────────────────────────────────────────────────────────

function generate({ resolved, check, log = () => {} }) {
  const registry = loadRegistry();
  fs.mkdirSync(CLIENTS_DIR, { recursive: true });

  const written = [];

  Object.keys(registry.clients).forEach((id) => {
    const client = resolveClient(id, registry);
    const file = path.join(CLIENTS_DIR, `${id}.xcconfig`);

    if (client.ios.icon && hasMaster(client.ios.icon) && !check) {
      written.push(...generateIcons(client.ios.icon));
    }

    if (!check) {
      const rendered = renderClientXcconfig(client, registry);
      assertValidXcconfig(rendered, `${id}.xcconfig`);
      fs.writeFileSync(file, rendered, 'utf8');
      written.push(file);

      // One shared scheme per client — the flavour picker in Xcode's toolbar.
      const scheme = path.join(SCHEMES_DIR, `${id}.xcscheme`);
      fs.writeFileSync(scheme, renderScheme(client), 'utf8');
      written.push(scheme);
    }
  });

  if (!check) {
    // Retire the old single scheme so the dropdown lists flavours, not a name
    // that silently builds whatever Client.xcconfig happens to say.
    fs.mkdirSync(SCHEMES_DIR, { recursive: true });
    const legacy = path.join(SCHEMES_DIR, LEGACY_SCHEME);
    if (fs.existsSync(legacy)) fs.rmSync(legacy);

    const active = path.join(CONFIG_DIR, 'Client.xcconfig');
    const rendered = renderActiveXcconfig(resolved);
    assertValidXcconfig(rendered, 'Client.xcconfig');
    fs.writeFileSync(active, rendered, 'utf8');
    written.push(active);
    log(`  xcconfig → ${rel(active)} → ${resolved.id}.xcconfig`);
    log(
      `  schemes  → ios/butruProject.xcodeproj/xcshareddata/xcschemes/{${Object.keys(
        registry.clients,
      ).join(', ')}}.xcscheme`,
    );
  }

  return written;
}

